"""Turn a symbolic witness into a runnable Foundry test skeleton.

A witness is only a lead until it runs. This module renders the smallest test
that reproduces the witness against the *supplied runtime bytecode*: it etches
the code at a fixed address, calls it with the witness calldata, and asserts the
recorded terminal outcome. It does not invent source, an ABI or a claim about the
target; it is a reproduction harness, not a finding.
"""

from __future__ import annotations

from dataclasses import dataclass

MASK = (1 << 256) - 1
TARGET = "0xB1AC"


def calldata_from_witness(witness: dict, *, words: int | None = None) -> bytes:
    """Encode ``cd0``..``cdN`` from a solver witness as 32-byte words."""
    indexed: dict[int, int] = {}
    for key, value in witness.items():
        if key.startswith("cd") and key[2:].isdigit():
            indexed[int(key[2:])] = int(value) & MASK
    count = max(indexed) + 1 if indexed else 0
    if words is not None:
        count = max(count, words)
    return b"".join(indexed.get(i, 0).to_bytes(32, "big") for i in range(count))


@dataclass(frozen=True)
class WitnessPoc:
    runtime_code: bytes
    calldata: bytes
    expect_revert: bool
    value: int = 0
    name: str = "BlackheartWitness"

    def to_dict(self) -> dict:
        return {
            "name": self.name,
            "runtime_code": "0x" + bytes(self.runtime_code).hex(),
            "calldata": "0x" + bytes(self.calldata).hex(),
            "expect_revert": self.expect_revert,
            "value": self.value,
        }

    def render(self) -> str:
        assertion = (
            'assertFalse(ok, "witness did not revert");'
            if self.expect_revert
            else 'assertTrue(ok, "witness did not return");'
        )
        return f"""// SPDX-License-Identifier: MIT
pragma solidity ^0.8.20;

// Generated by BLACKHEART from a symbolic witness. It proves reachability of the
// recorded terminal state on the runtime bytecode below. It is not a claim about
// the source and it is not a finding until it runs and the impact is priced.

interface Vm {{
    function etch(address target, bytes calldata code) external;
}}

contract {self.name}Test {{
    address private constant HEVM_ADDRESS =
        address(bytes20(uint160(uint256(keccak256("hevm cheat code")))));
    Vm private constant vm = Vm(HEVM_ADDRESS);

    function test_witness() public {{
        address target = address(uint160({TARGET}));
        vm.etch(target, hex"{bytes(self.runtime_code).hex()}");
        (bool ok,) = target.call{{value: {self.value}}}(hex"{bytes(self.calldata).hex()}");
        {assertion}
    }}
}}
"""


def witness_poc(runtime_code: bytes, witness: dict, *,
                expect_revert: bool | None = None,
                value: int = 0, name: str = "BlackheartWitness") -> WitnessPoc:
    """Build a PoC from a witness; default the expectation to its halt reason."""
    if expect_revert is None:
        expect_revert = witness.get("_halt") == "revert"
    return WitnessPoc(runtime_code=bytes(runtime_code),
                      calldata=calldata_from_witness(witness),
                      expect_revert=expect_revert, value=value, name=name)


@dataclass(frozen=True)
class DivergencePoc:
    vulnerable: bytes
    guarded: bytes
    calldata: bytes
    name: str = "BlackheartDivergence"

    def to_dict(self) -> dict:
        return {
            "name": self.name,
            "vulnerable": "0x" + bytes(self.vulnerable).hex(),
            "guarded": "0x" + bytes(self.guarded).hex(),
            "calldata": "0x" + bytes(self.calldata).hex(),
        }

    def render(self) -> str:
        return f"""// SPDX-License-Identifier: MIT
pragma solidity ^0.8.20;

// Generated by BLACKHEART from a differential divergence. It proves that the
// same calldata produces a different outcome, revert status or return value on
// the two runtime bytecodes below. It is a reproduction harness, not a finding.

interface Vm {{
    function etch(address target, bytes calldata code) external;
}}

contract {self.name}Test {{
    address private constant HEVM_ADDRESS =
        address(bytes20(uint160(uint256(keccak256("hevm cheat code")))));
    Vm private constant vm = Vm(HEVM_ADDRESS);

    function test_divergence() public {{
        address vulnerable = address(uint160(0xB1AC));
        address guarded = address(uint160(0xB1AD));
        vm.etch(vulnerable, hex"{bytes(self.vulnerable).hex()}");
        vm.etch(guarded, hex"{bytes(self.guarded).hex()}");
        (bool okVulnerable, bytes memory outVulnerable) = vulnerable.call(hex"{bytes(self.calldata).hex()}");
        (bool okGuarded, bytes memory outGuarded) = guarded.call(hex"{bytes(self.calldata).hex()}");
        assertTrue(
            okVulnerable != okGuarded
                || keccak256(outVulnerable) != keccak256(outGuarded),
            "the guarded twin did not diverge"
        );
    }}
}}
"""
