"""Forge-std-free symbolic harness generation for Halmos.

Halmos symbolically executes Foundry-style test functions and asks an SMT solver
whether an assertion can fail. It does **not** model forge-std cheatcodes
(``vm.deployCode``, ``vm.etch``, ``vm.prank`` ...). A harness that imports
forge-std therefore fails to run: the run is a tool failure, not a clean scan.
That is honest but useless -- the property was never actually explored.

The remedy is not to weaken the harness but to emit a *self-contained* one that
uses only plain Solidity: builtin ``assert``, a declared interface for the target,
and ordinary statements in ``setUp``. This module generates that text.

It generates text and nothing more. A generated harness is a *lead*: it lets
Halmos explore a property it could not otherwise reach. It is never a finding,
never a proof, and never evidence a property holds -- a symbolic "no
counterexample" is "none within the bound", exactly as the adapter records.

The generator is deliberately conservative: it refuses to emit a harness that
would itself depend on a cheatcode, so a caller cannot reintroduce the very
failure this module exists to remove.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any

#: Tokens that make a Halmos harness un-runnable. Any of these in a generated
#: harness is a configuration error the generator refuses to produce.
CHEATCODE_MARKERS: tuple[str, ...] = (
    "forge-std",
    "vm.deployCode",
    "deployCode",
    "vm.etch",
    "vm.store",
    "vm.mockCall",
    "vm.prank",
    "vm.startPrank",
    "vm.warp",
    "vm.roll",
    "cheats",
    "Test.sol",
)

#: Matches a Solidity identifier so generated names can be validated.
_IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


class HarnessError(ValueError):
    """A harness spec is invalid or would depend on an unmodelled cheatcode."""


@dataclass
class SymbolicHarnessSpec:
    """The minimal description of a forge-std-free symbolic harness.

    ``imports`` are Solidity source paths (relative to the project root), e.g.
    ``["src/Vault.sol"]``. ``target_decl`` is an optional inline interface /
    type declaration (for an undeployed address). ``setup`` are plain Solidity
    statements run once; ``checks`` are ``(name, expression)`` pairs, each
    emitted as a ``check_<name>()`` that ``assert``s ``expression``.
    """

    contract_name: str
    imports: list[str] = field(default_factory=list)
    target_decl: str = ""
    setup: list[str] = field(default_factory=list)
    checks: list[tuple[str, str]] = field(default_factory=list)
    pragma: str = "^0.8.20"

    def to_dict(self) -> dict[str, Any]:
        return {
            "contract_name": self.contract_name,
            "imports": list(self.imports),
            "target_decl": self.target_decl,
            "setup": list(self.setup),
            "checks": [list(c) for c in self.checks],
            "pragma": self.pragma,
        }


def _validate(spec: SymbolicHarnessSpec) -> None:
    if not _IDENT.match(spec.contract_name):
        raise HarnessError(f"invalid contract name: {spec.contract_name!r}")
    if not spec.checks:
        raise HarnessError("a symbolic harness needs at least one check")
    seen: set[str] = set()
    for name, expr in spec.checks:
        if not _IDENT.match(name):
            raise HarnessError(f"invalid check name: {name!r}")
        if name in seen:
            raise HarnessError(f"duplicate check name: {name!r}")
        seen.add(name)
        if not expr.strip():
            raise HarnessError(f"check {name!r} has an empty assertion")
    # A spec that smuggles a cheatcode back in is rejected, not silently emitted.
    blob = "\n".join([spec.target_decl, *spec.setup, *(e for _, e in spec.checks)])
    lowered = blob.lower()
    for marker in CHEATCODE_MARKERS:
        if marker.lower() in lowered:
            raise HarnessError(
                f"spec depends on unmodelled cheatcode/import {marker!r}; "
                "emit a plain-Solidity harness instead"
            )


def render_harness(spec: SymbolicHarnessSpec) -> str:
    """Render ``spec`` as a self-contained ``.t.sol`` with no forge-std.

    The output uses builtin ``assert`` only, so Halmos can explore it without the
    cheatcodes it does not model. Raises :class:`HarnessError` if the spec is
    invalid or would reintroduce a cheatcode dependency.
    """
    _validate(spec)
    lines: list[str] = [
        "// SPDX-License-Identifier: MIT",
        f"pragma solidity {spec.pragma};",
        "",
        "// Generated by blackheart.symbolic.harness -- self-contained by design.",
        "// Halmos explores each check_*() and reports a counterexample if the",
        "// assertion is violable. No external test library, no host-call helpers.",
    ]
    for path in spec.imports:
        lines.append(f'import {{ }} from "{path}";  // ensures the target is compiled')
    lines.append("")
    lines.append(f"contract {spec.contract_name} {{")
    if spec.target_decl.strip():
        for raw in spec.target_decl.strip().splitlines():
            lines.append(f"    {raw}")
        lines.append("")
    lines.append("    function setUp() public {")
    if spec.setup:
        for stmt in spec.setup:
            for raw in stmt.rstrip().splitlines():
                lines.append(f"        {raw}")
    else:
        lines.append("        // no setup required")
    lines.append("    }")
    for name, expr in spec.checks:
        lines.append("")
        lines.append(f"    function check_{name}() public {{")
        lines.append(f"        assert({expr});")
        lines.append("    }")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def harness_from_dict(data: dict[str, Any]) -> SymbolicHarnessSpec:
    """Build a :class:`SymbolicHarnessSpec` from a plain dict (CLI / JSON input)."""
    if not isinstance(data, dict):
        raise HarnessError("harness spec must be a JSON object")
    checks_raw = data.get("checks") or []
    checks: list[tuple[str, str]] = []
    for item in checks_raw:
        if isinstance(item, dict):
            checks.append((str(item.get("name", "")), str(item.get("expression", ""))))
        elif isinstance(item, (list, tuple)) and len(item) == 2:
            checks.append((str(item[0]), str(item[1])))
        else:
            raise HarnessError(f"invalid check entry: {item!r}")
    return SymbolicHarnessSpec(
        contract_name=str(data.get("contract_name") or ""),
        imports=[str(p) for p in (data.get("imports") or [])],
        target_decl=str(data.get("target_decl") or ""),
        setup=[str(s) for s in (data.get("setup") or [])],
        checks=checks,
        pragma=str(data.get("pragma") or "^0.8.20"),
    )


def detect_cheatcodes(source: str) -> list[str]:
    """Return the cheatcode/forge-std markers present in ``source`` (sorted, unique).

    Used to explain *why* an existing harness cannot run under Halmos, and by the
    adapter to recognise that failure mode from the tool's own output.
    """
    lowered = source.lower()
    return sorted({m for m in CHEATCODE_MARKERS if m.lower() in lowered})
